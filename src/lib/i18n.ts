export function t(text: string): string {
  return translate(text, useSettingsStore.getState().language);
}

export function translate(text: string, language: Language): string {
  return language === 'zh-CN' ? (zhCN[text] ?? text) : text;
}

export function translateStaticText(
  text: string,
  count: string | undefined,
  language: Language,
): string {
  return translate(text, language).replace('{count}', count ?? '{count}');
}
